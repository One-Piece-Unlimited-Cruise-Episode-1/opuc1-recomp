// PC versions of the PlayGuide pictures, ported from the Play tab (programs/apps/play/web/play/ui/pcguide.js; not
// in the game). The game's pictures (PlayDispContent.aar 0xA00498-0xA0049E, vault entities/menus.md "PlayGuide
// pictures, as images") show Wii Remote buttons and motions. Each PC picture keeps its game picture's title strip
// (the gold word and the white rule), the teal panel of 0xA00499 stretched to the new height, and captions set from
// the letters cut out of the game pictures' own baked caption lines; the key / mouse glyph rows are the Play tab's
// keyglyph.js art (fishing_glyphs.inc, generated by tools/fishing_glyphs). Pure image code on straight RGBA.
#pragma once

#include <algorithm>
#include <cmath>
