// Generator for runtime/src/hle/opuc/pc_art.inc: the PC button art of the Play tab (programs/apps/play/web/play/ui/
// pcart.js) for the recompilation. The page runs the Play tab's own PcArt on the game's pictures and splits each
// result in two: the drawing operations that use the game picture (copies, stretches, mirrors, clears: plain geometry,
// no pixels) and a transparent layer with only the key / mouse glyphs (keyglyph.js art). The runtime replays the
// operations on the user's own disc pictures and lays the glyph layer over them (hle/opuc/pc_art.cpp), so no game
// pixels are stored. Run: node programs/Recomp/tools/pcart_gen/serve.mjs, open http://localhost:8791/; the page posts
// the result back, this server writes the .inc and exits. Serves the Play app's modules and the extracted disc the way
// the Play server does (/play/..., /shared/web/..., /files/...).
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const recomp = path.resolve(here, '..', '..');
const apps = path.resolve(recomp, '..', 'apps');
const files = path.join(recomp, 'data', 'extract', 'DATA', 'files');
const out = path.join(recomp, 'runtime', 'src', 'hle', 'opuc', 'pc_art.inc');
const port = Number(process.env.PORT || 8791);
const types = { '.js': 'text/javascript', '.mjs': 'text/javascript', '.html': 'text/html', '.json': 'application/json' };

function under(root, rel) {
    const p = path.resolve(root, rel);
    return p.startsWith(root) ? p : null;
}

function hex(bytes) {
    const lines = [];
    for (let i = 0; i < bytes.length; i += 24) lines.push('    ' + [...bytes.subarray(i, i + 24)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',') + ',');
    return lines.join('\n');
}

function writeInc(pics) {
    const L = [
        '// Generated by tools/pcart_gen (node serve.mjs + the browser page) from the Play tab\'s play/ui/pcart.js and',
        '// keyglyph.js, with the recompilation\'s fixed keys. Per picture: the source picture size it was made for, the output',
        '// size, the drawing operations on the game picture (geometry only) and the glyph layer (straight RGBA, cropped; no',
        '// game pixels). Do not edit by hand.',
        '',
        'struct PcArtOp { uint8_t kind; uint8_t smooth; float sx, sy, sw, sh, dx, dy, dw, dh; float m[6]; };  // kind 0 drawImage, 1 clearRect (dx..dh)',
        'struct PcArtPic { const char* file; uint32_t id; uint16_t srcW, srcH, w, h; const PcArtOp* ops; uint32_t opCount;',
        '                  int16_t gx, gy; uint16_t gw, gh; const uint8_t* glyph; };',
        '',
    ];
    const f = v => (Number.isInteger(v) ? `${v}.f` : `${+v.toFixed(5)}f`);
    pics.forEach((p, i) => {
        L.push(`static const PcArtOp kPcArtOps${i}[] = {`);
        for (const o of p.ops) L.push(`    {${o.kind}, ${o.smooth ? 1 : 0}, ${[o.sx, o.sy, o.sw, o.sh, o.dx, o.dy, o.dw, o.dh].map(f).join(', ')}, {${o.m.map(f).join(', ')}}},`);
        if (!p.ops.length) L.push('    {0, 0, 0.f, 0.f, 0.f, 0.f, 0.f, 0.f, 0.f, 0.f, {1.f, 0.f, 0.f, 1.f, 0.f, 0.f}},');
        L.push('};');
        const g = Buffer.from(p.glyph.data, 'base64');
        L.push(`static const uint8_t kPcArtGlyph${i}[${Math.max(1, g.length)}] = {`, g.length ? hex(g) : '    0', '};');
    });
    L.push('', 'static const PcArtPic kPcArtPics[] = {');
    pics.forEach((p, i) => L.push(`    {"${p.file}", 0x${p.id.toString(16).toUpperCase()}, ${p.srcW}, ${p.srcH}, ${p.w}, ${p.h}, kPcArtOps${i}, ${p.ops.length}, ${p.glyph.x}, ${p.glyph.y}, ${p.glyph.w}, ${p.glyph.h}, kPcArtGlyph${i}},`));
    L.push('};', '');
    fs.writeFileSync(out, L.join('\n'));
    console.log(`wrote ${out} (${pics.length} pictures)`);
}

http.createServer((req, res) => {
    const url = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (req.method === 'POST') {
        let body = '';
        req.on('data', c => (body += c));
        req.on('end', () => {
            try {
                const j = JSON.parse(body);
                if (url === '/survey') { console.log('SURVEY ' + JSON.stringify(j)); res.end('ok'); return; }
                if (url === '/out') { writeInc(j); res.end('ok'); setTimeout(() => process.exit(0), 200); return; }
            } catch (e) { res.statusCode = 500; res.end(String(e)); return; }
            res.statusCode = 404; res.end();
        });
        return;
    }
    let file = null;
    if (url === '/' || url === '/generate.html') file = path.join(here, 'generate.html');
    else if (url.startsWith('/files/')) file = under(files, url.slice(7));
    else if (url.startsWith('/shared/web/')) file = under(path.join(apps, 'shared', 'web'), url.slice(12));
    else file = under(path.join(apps, 'play', 'web'), url.slice(1));
    if (!file || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); res.end('not found'); return; }
    res.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
    fs.createReadStream(file).pipe(res);
}).listen(port, () => console.log(`pc art generator on http://localhost:${port}/`));
