// Generator for runtime/src/hle/opuc/fishing_glyphs.inc: the PC key / mouse glyph rows of the fishing and tool
// PlayGuide pictures, drawn by the Play tab's own glyph code (programs/apps/play/web/play/ui/keyglyph.js) in a
// browser. The rows hold no game pixels; the runtime puts them on pictures it rebuilds from the game's own
// (hle/opuc/fishing_pc.cpp). Run: node programs/Recomp/tools/fishing_glyphs/serve.mjs, open http://localhost:8790/,
// the page posts the rows back and this server writes the .inc file, then exits.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const recomp = path.resolve(here, '..', '..');
const keyglyph = path.resolve(recomp, '..', 'apps', 'play', 'web', 'play', 'ui', 'keyglyph.js');
const out = path.join(recomp, 'runtime', 'src', 'hle', 'opuc', 'fishing_glyphs.inc');
const port = Number(process.env.PORT || 8790);

function writeInc(rows) {
    const lines = [
        '// Generated by tools/fishing_glyphs (node serve.mjs + the browser page): the PC key / mouse glyph rows of the',
        '// PlayGuide pictures, drawn by programs/apps/play/web/play/ui/keyglyph.js (TEAL palette, 22-px key caps).',
        '// Straight (not premultiplied) RGBA, cropped; x / y are the crop origin in a 156-wide row whose top is the row',
        '// top of play/ui/pcguide.js build() (the glyphs sit at row top + 4). No game pixels. Do not edit by hand.',
        '',
    ];
    for (const r of rows) {
        const bytes = Buffer.from(r.data, 'base64');
        lines.push(`static const uint8_t kGlyph_${r.name}_rgba[${bytes.length}] = {`);
        for (let i = 0; i < bytes.length; i += 24) lines.push('    ' + [...bytes.subarray(i, i + 24)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',') + ',');
        lines.push('};');
    }
    lines.push('', 'struct GlyphRow { const char* name; int x, y, w, h; const uint8_t* rgba; };');
    lines.push('static const GlyphRow kGlyphRows[] = {');
    for (const r of rows) lines.push(`    {"${r.name}", ${r.x}, ${r.y}, ${r.w}, ${r.h}, kGlyph_${r.name}_rgba},`);
    lines.push('};', '');
    fs.writeFileSync(out, lines.join('\n'));
    console.log(`wrote ${out} (${rows.length} rows)`);
}

http.createServer((req, res) => {
    if (req.method === 'POST' && req.url === '/out') {
        let body = '';
        req.on('data', c => (body += c));
        req.on('end', () => {
            try { writeInc(JSON.parse(body)); res.end('ok'); } catch (e) { res.statusCode = 500; res.end(String(e)); return; }
            setTimeout(() => process.exit(0), 200);
        });
        return;
    }
    const file = req.url === '/keyglyph.js' ? keyglyph : path.join(here, 'generate.html');
    res.setHeader('Content-Type', file.endsWith('.js') ? 'text/javascript' : 'text/html');
    fs.createReadStream(file).pipe(res);
}).listen(port, () => console.log(`fishing glyph generator on http://localhost:${port}/`));
